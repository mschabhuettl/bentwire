// ----- rendering and the package -----

/// One picture in `style` at density `k` (modern) or hard 1x (retro). Modern: RGBA bytes;
/// retro: indices into the palette of `roles`.
fn render(
    shapes: &[raster::Shape],
    w: u32,
    h: u32,
    k: u32,
    origin: raster::P,
    style: Style,
    roles: &'static [Role],
) -> Vec<u8> {
    let hard = style == Style::Retro;
    let mut cv = Canvas::new(w * k, h * k, k as f64, origin, hard, roles);
    for s in shapes {
        cv.draw(s);
    }
    if hard { cv.indices() } else { cv.rgba() }
}

/// A PNG of `w` x `h` RGBA bytes (modern) or indices into the palette of `roles` (retro).
fn png(w: u32, h: u32, buf: &[u8], style: Style, roles: &[Role]) -> Result<Vec<u8>, Error> {
    Ok(match style {
        Style::Modern => encode_png_rgba(w, h, buf)?,
        Style::Retro => {
            let mut trns = vec![255u8; roles.len() + 1];
            trns[0] = 0;
            encode_png_indexed(w, h, buf, &raster::palette(roles), Some(&trns))?
        }
    })
}

/// A sheet of `pics` (each `cell` at density `k`; RGBA or indices), as many columns as fit
/// 4096 px at 1x.
fn sheet_png(
    pics: &[&Vec<u8>],
    cell: [u32; 2],
    k: u32,
    style: Style,
    roles: &[Role],
) -> Result<Vec<u8>, Error> {
    let bpp = if style == Style::Retro { 1 } else { 4 };
    let (cw, ch) = (cell[0] * k, cell[1] * k);
    let cols = (4096 / cell[0]).min(pics.len() as u32).max(1);
    let rows = (pics.len() as u32).div_ceil(cols);
    let (w, h) = (cw * cols, ch * rows);
    let mut buf = vec![0u8; (w * h * bpp) as usize];
    for (n, p) in pics.iter().enumerate() {
        let (ox, oy) = ((n as u32 % cols) * cw, (n as u32 / cols) * ch);
        let row = (cw * bpp) as usize;
        for y in 0..ch {
            let d = (((oy + y) * w + ox) * bpp) as usize;
            let s = y as usize * row;
            buf[d..d + row].copy_from_slice(&p[s..s + row]);
        }
    }
    png(w, h, &buf, style, roles)
}

impl Design {
    /// Build the character in `style`.
    pub fn build(&self, style: Style) -> Result<PackageData, Error> {
        let retro = style == Style::Retro;
        let mut anims = animations();
        (self.adapt)(&mut anims);
        let densities: &[u32] = if retro { &[1] } else { &[1, 2] };
        let frame_picture = |p: &Pose, k: u32| {
            render(
                &(self.shapes)(p, retro),
                SIZE,
                SIZE,
                k,
                (0.0, 0.0),
                style,
                self.roles,
            )
        };
        // Distinct pictures, by pixels at 1x; each pose is drawn once.
        let mut pics: Vec<Vec<Vec<u8>>> = Vec::new();
        let mut seen: Vec<(Pose, u32)> = Vec::new();
        let mut index_of = |p: &Pose| -> u32 {
            if let Some(&(_, i)) = seen.iter().find(|(q, _)| q == p) {
                return i;
            }
            let one = frame_picture(p, 1);
            let i = match pics.iter().position(|d| d[0] == one) {
                Some(i) => i as u32,
                None => {
                    let mut d = vec![one];
                    d.extend(densities[1..].iter().map(|&k| frame_picture(p, k)));
                    pics.push(d);
                    (pics.len() - 1) as u32
                }
            };
            seen.push((*p, i));
            i
        };
        let lay = |sheet: &str, i: u32, x: i32, y: i32| Layer {
            image: ImageRef {
                sheet: sheet.into(),
                index: i,
            },
            x,
            y,
            size: None,
        };
        let mouth = self.mouth;
        let mut m = crate::build::empty_manifest(Family::Agent, [SIZE, SIZE]);
        m.character.info = (self.info)(style);
        m.balloon = Some(Balloon {
            enabled: Some(true),
            lines: Some(2),
            chars_per_line: Some(32),
            fg: Some("#000000".into()),
            bg: Some("#FFFFE1".into()),
            border: Some("#000000".into()),
            font: Some("Tahoma".into()),
            font_height: Some(-11),
            font_weight: Some(400),
            italic: Some(false),
            size_to_text: Some(true),
            auto_hide: Some(true),
            auto_pace: Some(true),
            ..Default::default()
        });
        for a in &anims {
            let n = a.frames.len();
            let mut frames = Vec::with_capacity(n);
            for (i, (p, ms)) in a.frames.iter().enumerate() {
                let mut f = Frame {
                    ms: *ms,
                    layers: vec![lay("a", index_of(p), 0, 0)],
                    ..Frame::default()
                };
                if p.upright() {
                    // The neutral mouth is its own layer so that a mouth overlay replaces it.
                    let (x, y) = (self.mouth_at)(p);
                    f.layers.push(lay("m", 7, x, y));
                    if a.mouths {
                        f.mouths = (0..7)
                            .map(|t| Mouth {
                                kind: t,
                                layer: lay("m", t as u32, x, y),
                                anchor: Some([x + mouth[0] as i32 / 2, y + mouth[1] as i32 / 2]),
                                base: None,
                            })
                            .collect();
                    }
                }
                if i == 0 {
                    f.sound = a.sound.map(String::from);
                }
                f.exit = match a.tail {
                    None => Some(Exit::End),
                    Some(_) if i + 1 == n => Some(Exit::End),
                    Some(t) if i < t => Some(Exit::Frame(t as u32)),
                    Some(_) => None,
                };
                f.branch = a
                    .branches
                    .iter()
                    .filter(|b| b.0 == i)
                    .map(|b| Branch::Random {
                        target: b.1 as u32,
                        p: b.2,
                    })
                    .collect();
                frames.push(f);
            }
            m.animations.push(Animation {
                name: a.name.clone(),
                transition: Some(a.transition),
                return_animation: a.ret.clone(),
                frames,
            });
        }
        m.states = STATES
            .iter()
            .map(|(s, l)| (s.to_string(), l.iter().map(|x| x.to_string()).collect()))
            .collect();

        // Sheets: frames in `a`, mouths in `m`; the modern style with 2x sheets.
        let mouths: Vec<Vec<Vec<u8>>> = (0..8)
            .map(|t| {
                let s = (self.mouth_shapes)(t, retro);
                densities
                    .iter()
                    .map(|&k| render(&s, mouth[0], mouth[1], k, (0.0, 0.0), style, self.roles))
                    .collect()
            })
            .collect();
        let mut files = Vec::new();
        for (id, cell, set) in [("a", [SIZE, SIZE], &pics), ("m", mouth, &mouths)] {
            let mut hidpi = std::collections::BTreeMap::new();
            for (j, &k) in densities.iter().enumerate() {
                let level: Vec<&Vec<u8>> = set.iter().map(|d| &d[j]).collect();
                let png = sheet_png(&level, cell, k, style, self.roles)?;
                let f = if k == 1 {
                    format!("sheets/{id}.png")
                } else {
                    format!("sheets/{id}@{k}x.png")
                };
                if k > 1 {
                    hidpi.insert(k, f.clone());
                }
                files.push((f, png));
            }
            m.sheets.push(Sheet {
                id: id.into(),
                file: format!("sheets/{id}.png"),
                cell,
                count: set.len() as u32,
                sizes: None,
                scale: None,
                hidpi,
            });
        }
        for (id, pcm) in (self.sounds)() {
            let f = format!("sounds/{id}.flac");
            files.push((f.clone(), encode_flac(&pcm)?));
            m.sounds.push((id.into(), f));
        }
        // Tray icon: the head at 32 x 32.
        let (origin, k) = (self.icon_view)();
        let mut cv = Canvas::new(32, 32, k, origin, retro, self.roles);
        for s in (self.shapes)(&REST, retro) {
            cv.draw(&s);
        }
        for s in (self.mouth_shapes)(7, retro) {
            // The neutral mouth layer, shifted to the rest pose's mouth.
            let (x, y) = (self.mouth_at)(&REST);
            cv.draw(&s.scaled((0.0, 0.0), 1.0, (x as f64, y as f64)));
        }
        let icon = if retro { cv.indices() } else { cv.rgba() };
        files.push(("icon.png".into(), png(32, 32, &icon, style, self.roles)?));
        m.icon = Some(IconRef {
            file: "icon.png".into(),
        });
        files.push(("LICENSE".into(), LICENCE.as_bytes().to_vec()));
        m.source = Some(
            [
                ("format", toml::Value::from("generated")),
                (
                    "generator",
                    toml::Value::from("cargo run -p bentwire-convert --bin gen-builtin"),
                ),
                ("licence", toml::Value::from("CC0-1.0")),
            ]
            .into_iter()
            .map(|(k, v)| (k.to_owned(), v))
            .collect(),
        );
        let errs = validate(&m);
        if !errs.is_empty() {
            return Err(Error::Invalid(errs));
        }
        Ok(PackageData {
            manifest: m,
            header: vec![
                format!(
                    "{} ({}), bentwire's own character, generated by `cargo run -p bentwire-convert --bin gen-builtin`",
                    self.name,
                    match style {
                        Style::Modern => "modern",
                        Style::Retro => "retro",
                    }
                ),
                format!(
                    "from the vector rig in crates/bentwire-convert/src/{}/. CC0-1.0 (see LICENSE).",
                    self.id
                ),
            ],
            files,
        })
    }
}
