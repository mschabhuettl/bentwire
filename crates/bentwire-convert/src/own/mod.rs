//! bentwire's own CC0 characters (architecture A-CHAR-1), such as Wire ([`crate::wire`]):
//! each is described once as a vector rig ([`Design`]) and rendered by code ([`raster`]) in
//! two styles: `<id>` (modern: anti-aliased, real alpha, 1x and 2x sheets) and `<id>-retro`
//! (indexed sheets with the character's few colours and transparent; hard edges, 1x). One
//! animation table of [`pose::Pose`]s drives them all. Deterministic: same code, same bytes.

