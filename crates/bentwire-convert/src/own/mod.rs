/// Canvas size of every own character.
pub const SIZE: u32 = 128;

/// The two renderings of the rig.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Style {
    Modern,
    Retro,
}

/// What one own character brings to the shared table and packaging.
pub struct Design {
    /// Id of the modern rendering; the retro one is `<id>-retro`.
    pub id: &'static str,
    pub name: &'static str,
    pub(crate) shapes: fn(&Pose, bool) -> Vec<raster::Shape>,
    /// Top-left of the mouth picture on an upright pose.
    pub(crate) mouth_at: fn(&Pose) -> (i32, i32),
    /// Mouth pictures 0..6 (Agent mouth types) and 7, the neutral mouth layer.
    pub(crate) mouth_shapes: fn(u8, bool) -> Vec<raster::Shape>,
    /// Mouth picture cell.
    pub(crate) mouth: [u32; 2],
    /// The tray icon's view: origin and pixels per unit.
    pub(crate) icon_view: fn() -> (raster::P, f64),
    /// The retro palette after transparent.
    pub(crate) roles: &'static [Role],
    pub(crate) info: fn(Style) -> Vec<Info>,
    /// Sounds by id, in manifest order.
    pub(crate) sounds: fn() -> Vec<(&'static str, Pcm)>,
    /// The character's own changes to the shared animation table (same names and states).
    pub(crate) adapt: fn(&mut [Anim]),
}

impl Design {
    pub fn id(&self, style: Style) -> String {
        match style {
            Style::Modern => self.id.into(),
            Style::Retro => format!("{}-retro", self.id),
        }
    }
}

/// `character.info` in English and German, each as name, description and intro phrases.
pub(crate) fn info(en: [&str; 3], de: [&str; 3]) -> Vec<Info> {
    [("en", en), ("de", de)]
        .into_iter()
        .map(|(lang, [name, d, x])| Info {
            lang: lang.into(),
            name: name.into(),
            description: Some(d.into()),
            extra: Some(x.into()),
        })
        .collect()
}

