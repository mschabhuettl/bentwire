/// One picture of the rig in `style` at density `k` (modern) or hard 1x (retro). Modern:
/// RGBA bytes; retro: palette indices.
fn render(
    shapes: &[raster::Shape],
    w: u32,
    h: u32,
    k: u32,
    origin: raster::P,
    style: Style,
) -> Vec<u8> {
    let hard = style == Style::Retro;
    let mut cv = Canvas::new(w * k, h * k, k as f64, origin, hard);
    for s in shapes {
        cv.draw(s);
    }
    if hard { cv.indices() } else { cv.rgba() }
}

fn frame_picture(p: &Pose, k: u32, style: Style) -> Vec<u8> {
    render(
        &rig::shapes(p, style == Style::Retro),
        SIZE,
        SIZE,
        k,
        (0.0, 0.0),
        style,
    )
}

/// A sheet of `pics` (each `cell` at density `k`; RGBA or indices), as many columns as fit
/// 4096 px at 1x.
fn sheet_png(pics: &[&Vec<u8>], cell: [u32; 2], k: u32, style: Style) -> Result<Vec<u8>, Error> {
    let bpp = if style == Style::Retro { 1 } else { 4 };
    let (cw, ch) = (cell[0] * k, cell[1] * k);
    let cols = (4096 / cell[0]).min(pics.len() as u32).max(1);
    let rows = (pics.len() as u32).div_ceil(cols);
    let (w, h) = (cw * cols, ch * rows);
    let mut buf = vec![0u8; (w * h * bpp) as usize];
    for (n, p) in pics.iter().enumerate() {
        let (ox, oy) = ((n as u32 % cols) * cw, (n as u32 / cols) * ch);
        let row = (cw * bpp) as usize;
        for y in 0..ch {
            let d = (((oy + y) * w + ox) * bpp) as usize;
            let s = y as usize * row;
            buf[d..d + row].copy_from_slice(&p[s..s + row]);
        }
    }
    Ok(match style {
        Style::Modern => encode_png_rgba(w, h, &buf)?,
        Style::Retro => {
            let mut trns = vec![255u8; raster::ROLES.len() + 1];
            trns[0] = 0;
            encode_png_indexed(w, h, &buf, &raster::palette(), Some(&trns))?
        }
    })
}

