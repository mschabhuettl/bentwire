/// Build Wire in `style`.
pub fn wire(style: Style) -> Result<PackageData, Error> {
    let anims = animations();
    let densities: &[u32] = if style == Style::Retro { &[1] } else { &[1, 2] };
    // Distinct pictures, by pixels at 1x; each pose is drawn once.
    let mut pics: Vec<Vec<Vec<u8>>> = Vec::new();
    let mut seen: Vec<(Pose, u32)> = Vec::new();
    let mut index_of = |p: &Pose| -> u32 {
        if let Some(&(_, i)) = seen.iter().find(|(q, _)| q == p) {
            return i;
        }
        let one = frame_picture(p, 1, style);
        let i = match pics.iter().position(|d| d[0] == one) {
            Some(i) => i as u32,
            None => {
                let mut d = vec![one];
                d.extend(densities[1..].iter().map(|&k| frame_picture(p, k, style)));
                pics.push(d);
                (pics.len() - 1) as u32
            }
        };
        seen.push((*p, i));
        i
    };
    let lay = |sheet: &str, i: u32, x: i32, y: i32| Layer {
        image: ImageRef {
            sheet: sheet.into(),
            index: i,
        },
        x,
        y,
        size: None,
    };
    let mut m = crate::build::empty_manifest(Family::Agent, [SIZE, SIZE]);
    m.character.info = info(style);
    m.balloon = Some(Balloon {
        enabled: Some(true),
        lines: Some(2),
        chars_per_line: Some(32),
        fg: Some("#000000".into()),
        bg: Some("#FFFFE1".into()),
        border: Some("#000000".into()),
        font: Some("Tahoma".into()),
        font_height: Some(-11),
        font_weight: Some(400),
        italic: Some(false),
        size_to_text: Some(true),
        auto_hide: Some(true),
        auto_pace: Some(true),
        ..Default::default()
    });
    for a in &anims {
        let n = a.frames.len();
        let mut frames = Vec::with_capacity(n);
        for (i, (p, ms)) in a.frames.iter().enumerate() {
            let mut f = Frame {
                ms: *ms,
                layers: vec![lay("a", index_of(p), 0, 0)],
                ..Frame::default()
            };
            if p.upright() {
                // The smile is its own layer so that a mouth overlay replaces it.
                let (x, y) = rig::mouth_at(p);
                f.layers.push(lay("m", 7, x, y));
                if a.mouths {
                    f.mouths = (0..7)
                        .map(|t| Mouth {
                            kind: t,
                            layer: lay("m", t as u32, x, y),
                            anchor: Some([x + MOUTH[0] as i32 / 2, y + MOUTH[1] as i32 / 2]),
                            base: None,
                        })
                        .collect();
                }
            }
            if i == 0 {
                f.sound = a.sound.map(String::from);
            }
            f.exit = match a.tail {
                None => Some(Exit::End),
                Some(_) if i + 1 == n => Some(Exit::End),
                Some(t) if i < t => Some(Exit::Frame(t as u32)),
                Some(_) => None,
            };
            f.branch = a
                .branches
                .iter()
                .filter(|b| b.0 == i)
                .map(|b| Branch::Random {
                    target: b.1 as u32,
                    p: b.2,
                })
                .collect();
            frames.push(f);
        }
        m.animations.push(Animation {
            name: a.name.clone(),
            transition: Some(a.transition),
            return_animation: a.ret.clone(),
            frames,
        });
    }
    m.states = STATES
        .iter()
        .map(|(s, l)| (s.to_string(), l.iter().map(|x| x.to_string()).collect()))
        .collect();

    // Sheets: frames in `a`, mouths in `m`; the modern style with 2x sheets.
    let mouths: Vec<Vec<Vec<u8>>> = (0..8)
        .map(|t| {
            let s = rig::mouth_shapes(t, style == Style::Retro);
            densities
                .iter()
                .map(|&k| render(&s, MOUTH[0], MOUTH[1], k, (0.0, 0.0), style))
                .collect()
        })
        .collect();
    let mut files = Vec::new();
    for (id, cell, set) in [("a", [SIZE, SIZE], &pics), ("m", MOUTH, &mouths)] {
        let mut hidpi = std::collections::BTreeMap::new();
        for (j, &k) in densities.iter().enumerate() {
            let level: Vec<&Vec<u8>> = set.iter().map(|d| &d[j]).collect();
            let png = sheet_png(&level, cell, k, style)?;
            let f = if k == 1 {
                format!("sheets/{id}.png")
            } else {
                format!("sheets/{id}@{k}x.png")
            };
            if k > 1 {
                hidpi.insert(k, f.clone());
            }
            files.push((f, png));
        }
        m.sheets.push(Sheet {
            id: id.into(),
            file: format!("sheets/{id}.png"),
            cell,
            count: set.len() as u32,
            sizes: None,
            scale: None,
            hidpi,
        });
    }
    for (id, pcm) in [
        ("show", boing(260, 900, 4400)),
        ("hide", boing(800, 200, 3300)),
    ] {
        let f = format!("sounds/{id}.flac");
        files.push((f.clone(), encode_flac(&pcm)?));
        m.sounds.push((id.into(), f));
    }
    // Tray icon: the head at 32 x 32.
    let (origin, k) = rig::icon_view();
    let mut cv = Canvas::new(32, 32, k, origin, style == Style::Retro);
    for s in rig::shapes(&REST, style == Style::Retro) {
        cv.draw(&s);
    }
    for s in rig::mouth_shapes(7, style == Style::Retro) {
        // The smile layer, shifted to the rest pose's mouth.
        let (x, y) = rig::mouth_at(&REST);
        cv.draw(&shift(&s, x as f64, y as f64));
    }
    let icon = match style {
        Style::Modern => encode_png_rgba(32, 32, &cv.rgba())?,
        Style::Retro => {
            let mut trns = vec![255u8; raster::ROLES.len() + 1];
            trns[0] = 0;
            encode_png_indexed(32, 32, &cv.indices(), &raster::palette(), Some(&trns))?
        }
    };
    files.push(("icon.png".into(), icon));
    m.icon = Some(IconRef {
        file: "icon.png".into(),
    });
    files.push(("LICENSE".into(), LICENCE.as_bytes().to_vec()));
    m.source = Some(
        [
            ("format", toml::Value::from("generated")),
            (
                "generator",
                toml::Value::from("cargo run -p bentwire-convert --bin gen-builtin"),
            ),
            ("licence", toml::Value::from("CC0-1.0")),
        ]
        .into_iter()
        .map(|(k, v)| (k.to_owned(), v))
        .collect(),
    );
    let errs = validate(&m);
    if !errs.is_empty() {
        return Err(Error::Invalid(errs));
    }
    Ok(PackageData {
        manifest: m,
        header: vec![
            format!(
                "Wire ({}), bentwire's own character, generated by `cargo run -p bentwire-convert --bin gen-builtin`",
                match style {
                    Style::Modern => "modern",
                    Style::Retro => "retro",
                }
            ),
            "from the vector rig in crates/bentwire-convert/src/wire/. CC0-1.0 (see LICENSE)."
                .into(),
        ],
        files,
    })
}

fn shift(s: &raster::Shape, dx: f64, dy: f64) -> raster::Shape {
    use raster::Shape::*;
    let m = |p: &raster::P| (p.0 + dx, p.1 + dy);
    match s {
        Stroke(v, w, r) => Stroke(v.iter().map(m).collect(), *w, *r),
        Disc(c, r, role) => Disc(m(c), *r, *role),
        Ellipse(c, rx, ry, r) => Ellipse(m(c), *rx, *ry, *r),
        Polygon(v, r) => Polygon(v.iter().map(m).collect(), *r),
        Shadow(c, rx, ry, a) => Shadow(m(c), *rx, *ry, *a),
    }
}
