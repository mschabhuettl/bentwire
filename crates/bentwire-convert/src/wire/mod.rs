// ----- animation table -----

struct Anim {
    name: String,
    frames: Vec<(Pose, u32)>,
    /// Forward random branches: (frame, target, p). Only idle loops branch backwards.
    branches: Vec<(usize, usize, u32)>,
    /// Exit target of the frames before it (the wind-down); `None`: a return animation,
    /// whose frames all have `exit = "end"`.
    tail: Option<usize>,
    transition: Transition,
    ret: Option<String>,
    mouths: bool,
    sound: Option<&'static str>,
}

impl Anim {
    /// Plays once and ends on the rest pose; a Stop jumps to the last frame.
    fn plain(name: &str, frames: Vec<(Pose, u32)>) -> Anim {
        let n = frames.len();
        Anim {
            name: name.into(),
            frames,
            branches: vec![],
            tail: Some(n - 1),
            transition: Transition::None,
            ret: None,
            mouths: false,
            sound: None,
        }
    }

    fn tail(mut self, t: usize) -> Anim {
        self.tail = Some(t);
        self
    }

    fn branch(mut self, from: usize, to: usize, p: u32) -> Anim {
        self.branches.push((from, to, p));
        self
    }

    fn exit(mut self) -> Anim {
        self.transition = Transition::Exit;
        self
    }

    fn mouths(mut self) -> Anim {
        self.mouths = true;
        self
    }

    fn renamed(&self, name: &str) -> Anim {
        Anim {
            name: name.into(),
            frames: self.frames.clone(),
            branches: self.branches.clone(),
            tail: self.tail,
            transition: self.transition,
            ret: self.ret.clone(),
            mouths: self.mouths,
            sound: self.sound,
        }
    }
}

/// An animation that ends on a held pose, and its `<name>Return` back to rest (B-SW-A
/// case 2).
fn held(name: &str, to: Seq, back: Seq) -> [Anim; 2] {
    let ret = format!("{name}Return");
    let a = Anim {
        tail: None,
        transition: Transition::Return,
        ret: Some(ret.clone()),
        ..Anim::plain(name, to.0)
    };
    [a, Anim::plain(&ret, back.0)]
}

/// An idle loop: `lead` once, `body` repeating until stopped (100 % back branch), then
/// `tail` on the way out. Only for IdlingLevel members.
fn idle_loop(name: &str, lead: Seq, body: Seq, tail: Seq) -> Anim {
    let (l, b) = (lead.0.len(), body.0.len());
    let mut f = lead.0;
    f.extend(body.0);
    f.extend(tail.0);
    Anim::plain(name, f)
        .tail(l + b)
        .branch(l + b - 1, l, 100)
        .exit()
}

/// Frame list builder: each step eases from the last pose to the next.
#[derive(Clone)]
struct Seq(Vec<(Pose, u32)>);

impl Seq {
    fn at(p: Pose, ms: u32) -> Seq {
        Seq(vec![(p, ms)])
    }

    /// `n` frames from the last pose to `b` (the last of them is `b`), `ms` each.
    fn to(mut self, b: Pose, n: usize, ms: u32) -> Seq {
        let a = self.0.last().map_or(REST, |f| f.0);
        for i in 1..=n {
            self.0.push((a.tween(&b, i as f64 / n as f64), ms));
        }
        self
    }

    fn hold(mut self, ms: u32) -> Seq {
        self.0.last_mut().unwrap().1 += ms;
        self
    }

    fn then(mut self, s: Seq) -> Seq {
        self.0.extend(s.0);
        self
    }

    fn times(self, n: usize) -> Seq {
        let mut v = Vec::new();
        for _ in 0..n {
            v.extend(self.0.iter().copied());
        }
        Seq(v)
    }

    fn len(&self) -> usize {
        self.0.len()
    }
}

fn pose(f: impl FnOnce(&mut Pose)) -> Pose {
    let mut p = REST;
    f(&mut p);
    p
}

fn rest(ms: u32) -> Seq {
    Seq::at(REST, ms)
}

